export function shouldRotateAiAttemptId(state: {
  inProgress?: boolean;
  text?: string;
  error?: string;
}) {
  if (state.inProgress) return false;
  return Boolean(state.text || state.error);
}

const AI_ATTEMPT_ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export function isAiAttemptId(value: string) {
  return AI_ATTEMPT_ID_PATTERN.test(value);
}

export type AiUsage = {
  promptTokens?: number;
  completionTokens?: number;
};

export type AiProviderRequest = {
  taskType: AiTaskType;
  system: string;
  user: string;
  jsonSchemaName: string;
  maxOutputTokens: number;
};

export type AiProviderSuccess = {
  ok: true;
  provider: string;
  model: string;
  text: string;
  usage?: AiUsage;
  latencyMs: number;
};

export type AiProviderFailure = {
  ok: false;
  provider: string;
  model?: string;
  error: string;
  retryable: boolean;
  latencyMs: number;
};

export type AiProviderResult = AiProviderSuccess | AiProviderFailure;

export interface AiProvider {
  readonly id: string;
  readonly connected: boolean;
  complete(request: AiProviderRequest): Promise<AiProviderResult>;
}

export type CitedFact = {
  key: string;
  label: string;
  value: string;
  href?: string;
};

export type StructuredAiOutput = {
  text: string;
  stance: "FACT" | "RECOMMENDATION" | "MIXED";
  citedFactKeys: string[];
  notes?: string;
};

export type AiRunResult = {
  status: AiInteractionStatus;
  connected: boolean;
  provider: string | null;
  model: string | null;
  output: StructuredAiOutput | null;
  message: string;
  failureReason?: string;
  retryable: boolean;
  usage?: AiUsage;
  interactionId?: string;
};

